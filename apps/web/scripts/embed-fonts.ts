// Regenerates src/fonts.ts from the woff2 files in mockup/fonts/.
//
// The image ships one file: `bun server.js`, and the Dockerfile copies nothing else out of the build
// stage. So the fonts cannot be sidecar files on disk — they have to be inside the bundle, and the
// only way to put 110 KB of binary into a text import is base64. Run this after touching a font:
//
//   bun apps/web/scripts/embed-fonts.ts
//
// The licence is not embedded: OFL.txt is read from mockup/fonts/ at build time too and served as
// itself, so the text people can read stays the text the licence asks for.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FONTS = ["anybody.woff2", "atkinson-mono.woff2", "atkinson-next.woff2"];
const dir = join(import.meta.dir, "../../../mockup/fonts");

const entries = FONTS.map((name) => {
  const bytes = readFileSync(join(dir, name));
  return `  "${name}": ${JSON.stringify(bytes.toString("base64"))},`;
});

const ofl = readFileSync(join(dir, "OFL.txt"), "utf8");

const source = `// Generated by apps/web/scripts/embed-fonts.ts — do not edit by hand.
//
// The three self-hosted faces of the 1-bit language, as base64, and the licence that lets us ship
// them. They live here because the deployed image is one bundled file with nothing beside it.
// See that script for why, and mockup/fonts/ for the bytes this was made from.

export const FONT_BASE64: Record<string, string> = {
${entries.join("\n")}
};

export const FONT_LICENCE = ${JSON.stringify(ofl)};
`;

writeFileSync(join(import.meta.dir, "../src/fonts.ts"), source);
console.log(`wrote src/fonts.ts from ${FONTS.length} files in ${dir}`);
